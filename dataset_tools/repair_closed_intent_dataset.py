from __future__ import annotations

import argparse
import json
from pathlib import Path

try:
    from closed_intent_repair import (
        SCHEMA_VERSION,
        load_repair_config,
        repair_closed_intents,
        source_tree_paths,
    )
except ModuleNotFoundError:
    from dataset_tools.closed_intent_repair import (
        SCHEMA_VERSION,
        load_repair_config,
        repair_closed_intents,
        source_tree_paths,
    )


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Repair only closed_intent labels while preserving source trees and every other field."
    )
    source = parser.add_mutually_exclusive_group(required=True)
    source.add_argument("--batch-dir", default="", help="Batch generated by batch_generate_users.py.")
    source.add_argument("--run-dir", default="", help="Single run generated by run_end_to_end_dataset.py.")
    parser.add_argument("--output-dir", default="", help=f"Defaults to <source>/{SCHEMA_VERSION}.")
    parser.add_argument("--config", required=True, help="Private nested postprocess config or flat generation config.")
    parser.add_argument("--tree-offset", type=int, default=0)
    parser.add_argument("--limit-trees", type=int, default=0)
    return parser.parse_args()


def main() -> None:
    args = parse_args()
    batch_dir = Path(args.batch_dir).resolve() if args.batch_dir else None
    run_dir = Path(args.run_dir).resolve() if args.run_dir else None
    source_root = batch_dir or run_dir
    assert source_root is not None
    output_dir = Path(args.output_dir).resolve() if args.output_dir else source_root / SCHEMA_VERSION
    paths = source_tree_paths(batch_dir=batch_dir, run_dir=run_dir)
    if args.tree_offset > 0:
        paths = paths[args.tree_offset :]
    if args.limit_trees > 0:
        paths = paths[: args.limit_trees]
    summary = repair_closed_intents(
        source_root=source_root,
        tree_paths=paths,
        output_dir=output_dir,
        config=load_repair_config(Path(args.config).resolve()),
    )
    print(json.dumps(summary, ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()
